#!/usr/bin/env python3
"""Build a note graph using only Python's standard library."""
import argparse
from collections import defaultdict
from datetime import datetime, timezone
import json
from pathlib import Path
import re
import tempfile

ROOT = Path(__file__).resolve().parent
WIKI = re.compile(r'\[\[([^\]]+)\]\]')


def canonical(value):
    value = value.split('|', 1)[0].split('#', 1)[0].strip().replace('\\', '/')
    if value.lower().endswith('.md'):
        value = value[:-3]
    return re.sub(r'\s+', ' ', value).casefold()


def excerpt(text):
    text = re.sub(r'^---\s*\n.*?\n---\s*\n', '', text, count=1, flags=re.S)
    text = WIKI.sub(lambda m: m.group(1).split('|')[-1].split('#')[0], text)
    text = re.sub(r'\[([^\]]+)\]\([^)]*\)', r'\1', text)
    text = re.sub(r'(?m)^\s{0,3}#{1,6}\s+', '', text)
    text = re.sub(r'\s+', ' ', text).strip()
    return text[:697].rstrip() + '…' if len(text) > 700 else text


def build_graph(notes):
    notes = notes.resolve()
    if not notes.is_dir():
        raise ValueError('Notes directory does not exist: ' + str(notes))
    paths = sorted((p for p in notes.rglob('*') if p.is_file() and p.suffix.lower() == '.md'), key=lambda p: p.relative_to(notes).as_posix().casefold())
    nodes, texts, targets = [], [], []
    for path in paths:
        if not path.resolve().is_relative_to(notes):
            raise ValueError('Note symlink points outside the notes directory: ' + str(path))
        text = path.read_text(encoding='utf-8-sig')
        relative = path.relative_to(notes)
        nodes.append({'id':len(nodes), 'label':path.stem, 'group':relative.parent.as_posix() if relative.parent != Path('.') else 'Notes', 'excerpt':excerpt(text), 'path':relative.as_posix()})
        texts.append(text)
        targets.append({canonical(m) for m in WIKI.findall(text) if canonical(m)})
    aliases = defaultdict(set)
    for node in nodes:
        aliases[canonical(node['label'])].add(node['id'])
        aliases[canonical(node['path'])].add(node['id'])
    edges = defaultdict(set)
    for i, node in enumerate(nodes):
        for target in targets[i]:
            for j in aliases.get(target, ()):
                if i != j:
                    edges[tuple(sorted((i, j)))].add('wikilink')
        for j, other in enumerate(nodes):
            if i == j:
                continue
            if re.search(r'(?<!\w)' + re.escape(other['label']) + r'(?!\w)', texts[i], re.I):
                edges[tuple(sorted((i, j)))].add('title mention')
            shared = targets[i] & targets[j]
            if shared:
                edges[tuple(sorted((i, j)))].add('shared wikilink')
    links = [{'source':i, 'target':j, 'reasons':sorted(reasons)} for (i,j), reasons in sorted(edges.items())]
    return {'nodes':nodes, 'links':links, 'meta':{'built_at':datetime.now(timezone.utc).isoformat(), 'note_count':len(nodes), 'link_count':len(links), 'source':notes.name, 'sample_count':sum('Fictional sample business: Harbor & Pine.' in text for text in texts)}}


def write_graph(graph, destination):
    destination.parent.mkdir(parents=True, exist_ok=True)
    content = '// Generated by build.py. Node ids equal their array positions.\nconst GRAPH = ' + json.dumps(graph, ensure_ascii=True, indent=2) + ';\n'
    with tempfile.NamedTemporaryFile('w', encoding='utf-8', dir=destination.parent, delete=False) as stream:
        temporary = Path(stream.name)
        stream.write(content)
    try:
        temporary.replace(destination)
    finally:
        temporary.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('notes', nargs='?', type=Path, default=ROOT/'notes')
    parser.add_argument('--output', type=Path, default=ROOT/'viewer/graph-data.js')
    args = parser.parse_args()
    try:
        graph = build_graph(args.notes)
        write_graph(graph, args.output)
    except (OSError, UnicodeError, ValueError) as error:
        parser.exit(1, 'Build failed: ' + str(error) + '\n')
    print(f"Indexed {len(graph['nodes'])} notes and {len(graph['links'])} links → {args.output}")


if __name__ == '__main__':
    main()
